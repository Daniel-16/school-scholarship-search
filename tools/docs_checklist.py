"""What the applicant has supplied, what each application still needs.

An application is rejected far more often for an incomplete file than for a
weak one, and the missing piece is almost never the statement - it is the
transcript that was never ordered, the referee who was never told, or the
test report that expired. Those are checkable facts about a directory, so
they are checked here rather than remembered.

Three subcommands:

  inventory    walk documents/ and report, per category, what is present and
               what the workflow is still waiting for. This is the answer to
               "what do you need from me", and it is derived from the tree,
               never from a list someone kept up to date by hand.
  check        read one application's requirements.json and say which required
               items are satisfied by something in documents/, which are
               missing, and which are expiring.
  scaffold     write a requirements.json for an application from one of the
               built-in requirement sets, so the common destinations do not
               have to be typed out each time.

Expiry is part of the check, not a footnote. An IELTS or TOEFL report is
valid for two years from the test date and a GRE score for five; a report
that expires between the application deadline and the start of the programme
is a real failure, and it is invisible unless someone does the arithmetic.
Dates come from a sidecar `<file>.meta.json` next to the document, because
nothing reliable can be read out of a scanned PDF.

Nothing here reads the contents of a document. It looks at names, sidecars
and counts - the applicant's transcripts and passport scans are not sent
anywhere or parsed, and `inventory` prints file names, never file contents.

Usage:
  python3 tools/docs_checklist.py inventory [--json]
  python3 tools/docs_checklist.py check <application-key> [--json] [--today YYYY-MM-DD]
  python3 tools/docs_checklist.py scaffold <application-key> --template uk-masters
  python3 tools/docs_checklist.py templates

Exit 0 when nothing is missing, 1 on a usage error, 3 when a required item is
missing or expired.
"""

