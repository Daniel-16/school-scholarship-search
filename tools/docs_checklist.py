def category_files(root: Path, category: str) -> list[Path]:
    folder = root / category
    if not folder.is_dir():
        return []
    return sorted(
        p for p in folder.rglob("*")
        if p.is_file() and p.name not in IGNORED_NAMES and not p.name.endswith(".meta.json")
    )


def sidecar(path: Path) -> dict:
    meta = path.with_name(path.name + ".meta.json")
    if not meta.is_file():
        return {}
    try:
        data = json.loads(meta.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def parse_iso(value) -> date | None:
    if not isinstance(value, str):
        return None
    try:
        return date.fromisoformat(value.strip())
    except ValueError:
        return None


def cmd_inventory(args) -> int:
    root = args.documents
    report, missing = [], []
    for name, spec in CATEGORIES.items():
        files = category_files(root, name)
        entry = {
            "category": name,
            "label": spec["label"],
            "files": [str(p.relative_to(root)) for p in files],
            "count": len(files),
            "wants": spec["wants"],
            "satisfied": bool(files),
        }
        if not files:
            missing.append(name)
        report.append(entry)

    result = {"documents_root": str(root), "categories": report, "missing_categories": missing}
    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        print(f"Document inventory - {root}\n")
        for entry in report:
            mark = "[x]" if entry["satisfied"] else "[ ]"
            print(f"  {mark} {entry['label']}  ({entry['count']} file(s) in documents/{entry['category']}/)")
            for name in entry["files"][:6]:
                print(f"        - {name}")
            if entry["count"] > 6:
                print(f"        ... and {entry['count'] - 6} more")
            if not entry["satisfied"]:
                print(f"        needed: {entry['wants']}")
        if missing:
            print(f"\n{len(missing)} categor{'y' if len(missing) == 1 else 'ies'} still empty: "
                  + ", ".join(missing))
        else:
            print("\nEvery category has at least one file.")
    return 3 if missing else 0


def cmd_check(args) -> int:
    folder = APPLICATIONS / args.key
    spec_path = folder / "requirements.json"
    if not spec_path.is_file():
        print(f"docs_checklist: {spec_path} not found - run `scaffold {args.key} --template <name>` first",
              file=sys.stderr)
        return 1
    try:
        spec = json.loads(spec_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"docs_checklist: cannot read {spec_path}: {exc}", file=sys.stderr)
        return 1

    items = spec.get("items")
    if not isinstance(items, list):
        print(f"docs_checklist: {spec_path}: expected an 'items' array", file=sys.stderr)
        return 1

    deadline = parse_iso(spec.get("deadline"))
    rows, blocking = [], []
    for item in items:
        if not isinstance(item, dict):
            continue
        category = item.get("category")
        required = bool(item.get("required", True))
        files = category_files(args.documents, category) if category else []
        row = {
            "item": item.get("id"),
            "category": category,
            "required": required,
            "note": item.get("note") or "",
            "files": [str(p.relative_to(args.documents)) for p in files],
            "status": "ok",
            "detail": "",
        }
        if category is None:
            # Produced by the workspace, not supplied: /apply writes it, and a
            # file in documents/ would not prove it exists for this programme.
            row["status"] = "produced_by_workflow"
        elif not files:
            row["status"] = "missing"
            row["detail"] = CATEGORIES.get(category, {}).get("wants", "")
        else:
            window = CATEGORIES.get(category, {}).get("expires")
            if window:
                # Validity is judged against the deadline, not against today:
                # a report that is valid now and expired by the deadline is
                # the failure this check exists for.
                against = deadline or args.today
                dated = [(f, parse_iso(sidecar(f).get("taken"))) for f in files]
                known = [(f, d + timedelta(days=window)) for f, d in dated if d]
                if not known:
                    row["status"] = "unknown_validity"
                    row["detail"] = ("no <file>.meta.json with a \"taken\" date, so validity "
                                     "cannot be checked")
                elif all(expiry < against for _, expiry in known):
                    row["status"] = "expired"
                    row["detail"] = ("every report expires before "
                                     f"{against.isoformat()} (latest {max(e for _, e in known).isoformat()})")
                else:
                    row["detail"] = f"valid until {max(e for _, e in known).isoformat()}"
        if required and row["status"] in ("missing", "expired"):
            blocking.append(row)
        rows.append(row)

    result = {
        "application": args.key,
        "template": spec.get("template"),
        "deadline": spec.get("deadline"),
        "items": rows,
        "blocking": [r["item"] for r in blocking],
    }
    if args.json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        print(f"Checklist - {args.key}"
              + (f"  (deadline {spec['deadline']})" if spec.get("deadline") else "") + "\n")
        marks = {"ok": "[x]", "missing": "[ ]", "expired": "[!]",
                 "unknown_validity": "[?]", "produced_by_workflow": "[~]"}
        for row in rows:
            flag = "" if row["required"] else "  (optional)"
            print(f"  {marks[row['status']]} {row['item']}{flag}")
            if row["note"]:
                print(f"        {row['note']}")
            if row["detail"]:
                print(f"        -> {row['detail']}")
        print()
        if blocking:
            print(f"{len(blocking)} required item(s) blocking: " + ", ".join(r["item"] for r in blocking))
        else:
            print("No required item is missing or expired.")
    return 3 if blocking else 0


def cmd_scaffold(args) -> int:
    if args.template not in TEMPLATES:
        print(f"docs_checklist: unknown template {args.template!r}; "
              f"one of {', '.join(sorted(TEMPLATES))}", file=sys.stderr)
        return 1
    folder = APPLICATIONS / args.key
    target = folder / "requirements.json"
    if target.exists() and not args.force:
        print(f"docs_checklist: {target} already exists - pass --force to overwrite", file=sys.stderr)
        return 1
    spec = {
        "application": args.key,
        "template": args.template,
        "deadline": args.deadline,
        "note": "Edit freely. The template is a starting point from the common pattern for this "
                "destination, never a substitute for reading the programme's own page.",
        "items": [
            {"id": item, "category": category, "required": required, "note": note}
            for item, category, required, note in TEMPLATES[args.template]
        ],
    }
    folder.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"saved={target}")
    return 0


def cmd_templates(args) -> int:
    for name, items in sorted(TEMPLATES.items()):
        required = sum(1 for _, _, r, _ in items if r)
        print(f"  {name:<22} {len(items)} items, {required} required")
    del args
    return 0


def _force_utf8_output() -> None:
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)  # absent on a StringIO under test
        if reconfigure:
            reconfigure(encoding="utf-8")


def main(argv=None) -> int:
    _force_utf8_output()
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--documents", type=Path, default=DOCS)
    common.add_argument("--json", action="store_true")

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="command", required=True)

    inv = sub.add_parser("inventory", parents=[common], help="what documents/ holds today")
    inv.set_defaults(func=cmd_inventory)

    chk = sub.add_parser("check", parents=[common], help="one application against its requirements.json")
    chk.add_argument("key")
    chk.add_argument("--today", type=date.fromisoformat, default=date.today())
    chk.set_defaults(func=cmd_check)

    sca = sub.add_parser("scaffold", parents=[common], help="write a requirements.json from a template")
    sca.add_argument("key")
    sca.add_argument("--template", required=True)
    sca.add_argument("--deadline", default=None)
    sca.add_argument("--force", action="store_true")
    sca.set_defaults(func=cmd_scaffold)

    tpl = sub.add_parser("templates", parents=[common], help="list the built-in requirement sets")
    tpl.set_defaults(func=cmd_templates)

    args = ap.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
